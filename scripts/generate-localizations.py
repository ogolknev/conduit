#!/usr/bin/env python3
"""Generate native macOS/Android catalogs and reject missing or damaged translations."""
import argparse, collections, hashlib, json, pathlib, re, sys
from xml.sax.saxutils import escape
p=argparse.ArgumentParser();p.add_argument('--check',action='store_true');args=p.parse_args()
root=pathlib.Path(__file__).resolve().parents[1]
catalog=json.loads((root/'localization/strings.json').read_text())

def resource(key):return 'text_'+hashlib.sha256(key.encode()).hexdigest()[:12]
def formats(text):return re.findall(r'%(?:\d+\$)?[@dsf]',text.replace('%%',''))
for key,values in catalog.items():
 assert set(values)=={'en','ru'} and all(isinstance(x,str) and x for x in values.values()), 'Missing translation: '+key
 assert formats(key)==formats(values['en'])==formats(values['ru']), 'Format mismatch: '+key
aliases=collections.defaultdict(list)
for key,values in catalog.items():
 for value in values.values():aliases[value].append(key)
files={}
for lang in ['en','ru']:
 entries={key:values[lang] for key,values in catalog.items()}
 for alias,keys in aliases.items():
  entries.setdefault(alias,catalog[keys[0]][lang])
 def quoted(s):return json.dumps(s,ensure_ascii=False)
 files[f'localization/{lang}.lproj/Localizable.strings']='// Generated by scripts/generate-localizations.py.\n'+''.join(quoted(k)+' = '+quoted(v)+';\n' for k,v in sorted(entries.items()))
 def xmltext(s):return escape(s.replace('\\','\\\\').replace("'","\\'").replace('"','\\"').replace('\n','\\n').replace('\t','\\t'))
 values='\n'.join('    <string name="'+resource(k)+'" formatted="false">'+'"'+xmltext(v[lang])+'"</string>' for k,v in catalog.items())
 files['android/res/'+('values' if lang=='en' else 'values-ru')+'/strings.xml']='<?xml version="1.0" encoding="utf-8"?>\n<!-- Generated by scripts/generate-localizations.py. -->\n<resources>\n'+values+'\n</resources>\n'
lookup={k:resource(k) for k in catalog}
for alias,keys in aliases.items():
 lookup.setdefault(alias,resource(keys[0]))
java='// Generated by scripts/generate-localizations.py.\npackage dev.conduit.bridge;\nimport java.util.Collections;\nimport java.util.HashMap;\nimport java.util.Map;\nfinal class LocalizedStrings {\n    static final Map<String,Integer> IDS;\n    static {\n        Map<String,Integer> values=new HashMap<>();\n'
java+=''.join('        values.put('+json.dumps(k,ensure_ascii=False)+',R.string.'+v+');\n' for k,v in sorted(lookup.items()))
java+='        IDS=Collections.unmodifiableMap(values);\n    }\n}\n'
files['android/src/dev/conduit/bridge/LocalizedStrings.java']=java
changed=[]
for name,text in files.items():
 path=root/name
 if not path.exists() or path.read_text()!=text:
  changed.append(name)
  if not args.check:path.parent.mkdir(parents=True,exist_ok=True);path.write_text(text)
if args.check and changed:sys.exit('Localization files out of date: '+', '.join(changed))
print(('Checked' if args.check else 'Generated'),len(catalog),'translations in',len(files),'native catalogs')
