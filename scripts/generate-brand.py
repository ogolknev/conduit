#!/usr/bin/env python3
"""Generate platform artwork from design/brand.json. --check rejects drift."""
import argparse, json, pathlib, sys
p=argparse.ArgumentParser();p.add_argument('--check',action='store_true');args=p.parse_args()
root=pathlib.Path(__file__).resolve().parents[1];b=json.loads((root/'design/brand.json').read_text())
rgb=[int(b['background'][i:i+2],16) for i in (1,3,5)]
g=b['glyph'];t=b['tile'];stroke=g['stroke'];half=stroke/2;canvas=b['canvas'];radius=g['radius'];bridge=g['bridge']
def f(n):return f'{n:.10g}'
def rect(x,y,w,h,r):
 return f'M{f(x+r)},{f(y)} H{f(x+w-r)} A{f(r)},{f(r)} 0,0 1,{f(x+w)},{f(y+r)} V{f(y+h-r)} A{f(r)},{f(r)} 0,0 1,{f(x+w-r)},{f(y+h)} H{f(x+r)} A{f(r)},{f(r)} 0,0 1,{f(x)},{f(y+h-r)} V{f(y+r)} A{f(r)},{f(r)} 0,0 1,{f(x+r)},{f(y)} Z'
paths=[rect(x-half,y-half,w+stroke,h+stroke,radius+half)+' '+rect(x+half,y+half,w-stroke,h-stroke,radius-half) for x,y,w,h in g['rects']]
paths.append(rect(bridge[0]-half,bridge[1]-half,bridge[2]-bridge[0]+stroke,stroke,half))
def svg(viewbox,tile=False):
 background=f'  <rect x="{t["x"]}" y="{t["y"]}" width="{t["size"]}" height="{t["size"]}" rx="{t["radius"]}" fill="{b["background"]}"/>\n' if tile else ''
 return '<svg xmlns="http://www.w3.org/2000/svg" width="1024" height="1024" viewBox="'+viewbox+'">\n'+background+''.join('  <path fill="#fff" fill-rule="evenodd" d="'+d+'"/>\n' for d in paths)+'</svg>\n'
def vector(scale,tile=False,size=24):
 background='    <path android:fillColor="'+b['background']+'" android:pathData="'+rect(t['x'],t['y'],t['size'],t['size'],t['radius'])+'" />\n' if tile else ''
 glyph=''.join('        <path android:fillColor="#FFFFFF" android:fillType="evenOdd" android:pathData="'+d+'" />\n' for d in paths)
 return f'<vector xmlns:android="http://schemas.android.com/apk/res/android" android:width="{size}dp" android:height="{size}dp" android:viewportWidth="{canvas}" android:viewportHeight="{canvas}">\n'+background+f'    <group android:scaleX="{f(scale)}" android:scaleY="{f(scale)}" android:pivotX="12" android:pivotY="12">\n'+glyph+'    </group>\n</vector>\n'
rects=', '.join('CGRect(x: '+f(x)+', y: '+f(y)+', width: '+f(w)+', height: '+f(h)+')' for x,y,w,h in g['rects'])
swift='''// Generated by scripts/generate-brand.py; edit design/brand.json.
import AppKit

enum BrandMark {
    static let canvas: CGFloat = CANVAS
    static let tile = CGRect(x: TX, y: TY, width: TS, height: TS)
    static let tileRadius: CGFloat = TR
    static let rectangles = [RECTS]
    static let radius: CGFloat = RADIUS
    static let stroke: CGFloat = STROKE
    static func drawGlyph(in context: CGContext, color: CGColor) {
        context.saveGState(); defer { context.restoreGState() }
        context.setStrokeColor(color); context.setLineWidth(stroke); context.setLineCap(.round); context.setLineJoin(.round)
        for rect in rectangles {
            context.addPath(CGPath(roundedRect: rect, cornerWidth: radius, cornerHeight: radius, transform: nil)); context.strokePath()
        }
        context.move(to: CGPoint(x: BX1, y: BY1)); context.addLine(to: CGPoint(x: BX2, y: BY2)); context.strokePath()
    }
    static func drawTile(in context: CGContext) {
        context.setFillColor(NSColor(srgbRed: BGR/255, green: BGG/255, blue: BGB/255, alpha: 1).cgColor)
        context.addPath(CGPath(roundedRect: tile, cornerWidth: tileRadius, cornerHeight: tileRadius, transform: nil)); context.fillPath()
        drawGlyph(in: context, color: NSColor.white.cgColor)
    }
    static func image(size: CGFloat = 32) -> NSImage {
        NSImage(size: NSSize(width: size, height: size), flipped: false) { _ in
            let context = NSGraphicsContext.current!.cgContext
            context.saveGState(); defer { context.restoreGState() }
            context.scaleBy(x: size/canvas, y: size/canvas); drawTile(in: context); return true
        }
    }
    static let menuBarImage: NSImage = {
        let size: CGFloat = MENUSIZE
        let glyphWidth: CGFloat = GLYPHWIDTH
        let scale: CGFloat = MENUWIDTH/glyphWidth
        let image = NSImage(size: NSSize(width: size, height: size), flipped: false) { _ in
            let context = NSGraphicsContext.current!.cgContext
            context.saveGState(); defer { context.restoreGState() }
            context.translateBy(x: size/2, y: size/2); context.scaleBy(x: scale, y: scale); context.translateBy(x: -canvas/2, y: -canvas/2)
            drawGlyph(in: context, color: NSColor.black.cgColor); return true
        }
        image.isTemplate = true; return image
    }()
}
'''
values={'BGR':rgb[0],'BGG':rgb[1],'BGB':rgb[2],'CANVAS':canvas,'TX':t['x'],'TY':t['y'],'TS':t['size'],'TR':t['radius'],'RECTS':rects,'RADIUS':radius,'STROKE':stroke,'BX1':bridge[0],'BY1':bridge[1],'BX2':bridge[2],'BY2':bridge[3],'MENUSIZE':b['menuCanvas'],'MENUWIDTH':b['menuGlyphWidth'],'GLYPHWIDTH':max(x+w for x,y,w,h in g['rects'])-min(x for x,y,w,h in g['rects'])+stroke}
import re
swift=re.sub(r'\b('+'|'.join(values)+r')\b',lambda m: f(values[m[0]]) if isinstance(values[m[0]],(int,float)) else values[m[0]],swift)
java='''// Generated by scripts/generate-brand.py; edit design/brand.json.
package dev.conduit.bridge;
import android.graphics.Canvas;
import android.graphics.Color;
import android.graphics.Paint;
final class BrandMark {
    static void drawTile(Canvas canvas, Paint paint) {
        int color=paint.getColor(); Paint.Style style=paint.getStyle(); float width=paint.getStrokeWidth();
        paint.setStyle(Paint.Style.FILL); paint.setColor(Color.rgb(BGR,BGG,BGB));
        canvas.drawRoundRect(TXf,TYf,TERf,TEBf,TRf,TRf,paint);
        paint.setStyle(Paint.Style.STROKE); paint.setColor(Color.WHITE); paint.setStrokeWidth(SWf);
RECTS
        canvas.drawLine(BX1f,BY1f,BX2f,BY2f,paint);
        paint.setColor(color); paint.setStyle(style); paint.setStrokeWidth(width);
    }
}
'''
vals={'TX':t['x'],'TY':t['y'],'TER':t['x']+t['size'],'TEB':t['y']+t['size'],'TR':t['radius'],'SW':stroke,'BX1':bridge[0],'BY1':bridge[1],'BX2':bridge[2],'BY2':bridge[3]}
for k,v in vals.items():java=java.replace(k+'f',f(v)+'f')
for k,v in zip(['BGR','BGG','BGB'],rgb):java=java.replace(k,str(v))
java=java.replace('RECTS','\n'.join('        canvas.drawRoundRect('+','.join(f(v)+'f' for v in [x,y,x+w,y+h,radius,radius])+',paint);' for x,y,w,h in g['rects']))
icon={'fill-specializations':[{'value':{'solid':'srgb:'+','.join(f(v/255) for v in rgb)+',1'}}], 'groups':[{'name':'Conduit','layers':[{'name':'Conduit','image-name':'Conduit.svg','glass':False}], 'shadow':{'kind':'neutral','opacity':0},'specular':False,'translucency':{'enabled':False,'value':0}}], 'supported-platforms':{'squares':['macOS']}}
files={'design/AppIcon.icon/icon.json':json.dumps(icon,indent=2)+'\n','android/res/values/colors.xml':'<resources>\n    <color name="conduit_icon_background">'+b['background']+'</color>\n</resources>\n','design/mark.svg':svg('0 0 24 24',True),'design/AppIcon.icon/Assets/Conduit.svg':svg(' '.join(f(t[k]) for k in ['x','y','size','size'])),
 'android/res/drawable/ic_launcher_foreground.xml':vector(b['androidAdaptiveScale'],size=108),
 'android/res/drawable/ic_notification.xml':vector(b['notificationScale']),
 'android/res/drawable/ic_conduit.xml':vector(1,True,108),
 'Sources/Conduit/BrandMark.swift':swift,'android/src/dev/conduit/bridge/BrandMark.java':java}
changed=[]
for name,content in files.items():
 path=root/name
 if not path.exists() or path.read_text()!=content:
  changed.append(name)
  if not args.check:path.write_text(content)
if args.check and changed:sys.exit('Brand assets out of date: '+', '.join(changed))
print(('Checked' if args.check else 'Generated'),len(files),'brand assets')
